//! Learned 256-pair rBRIEF sampling pattern for the ORB descriptor.
//!
//! Each pair gives two offsets `(p1, p2)` inside a 31×31 patch centered on a
//! keypoint. After rotating by the keypoint orientation, the descriptor bit
//! is `I(p1) < I(p2)` on the smoothed patch.
//!
//! Source: Rublee et al., "ORB: An efficient alternative to SIFT or SURF"
//! (ICCV 2011), as adopted verbatim by ORB-SLAM3. The pattern was learned on
//! ~300k keypoints to maximize per-bit variance (~0.5) and minimize inter-bit
//! correlation.

/// One BRIEF test: compare pixel at `p1` against pixel at `p2`.
#[derive(Clone, Copy, Debug)]
pub struct BriefPair {
    pub p1: (i8, i8),
    pub p2: (i8, i8),
}

impl BriefPair {
    const fn new(x1: i8, y1: i8, x2: i8, y2: i8) -> Self {
        Self {
            p1: (x1, y1),
            p2: (x2, y2),
        }
    }
}

